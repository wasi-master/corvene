#[test]
fn cargo_lock() {
    let new = CARGO_V3
        .replace("version = 3", "version = 4")
        .replace("1.0.200", "1.0.210")
        .replace("version = \"2.0.50\"", "version = \"2.0.60\"")
        .replace("syn 2.0.50", "syn 2.0.60")
        .replace("checksum = \"pm\"", "checksum = \"pm-changed\"")
        .replace(
            "1111111111111111111111111111111111111111",
            "2222222222222222222222222222222222222222",
        )
        + "\n[[package]]\nname = \"foo\"\nversion = \"0.3.1\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"f\"\n";
    let d = diff("Cargo.lock", CARGO_V3, &new);
    assert_eq!(d.ecosystem, Ecosystem::Cargo);
    assert_eq!(d.summary(), "2 upgraded, 1 added, 2 changed");
    assert_eq!(
        d.format_version_note().as_deref(),
        Some("Format version 3 → 4")
    );
    let serde = row(&d, "serde");
    assert_eq!(serde.version_label(), "1.0.200 → 1.0.210");
    assert_eq!(serde.direct, None);
    assert_eq!(
        serde.registry_url().as_deref(),
        Some("https://crates.io/crates/serde/1.0.210")
    );
    // syn 1 stays, syn 2 moves.
    assert_eq!(row(&d, "syn").version_label(), "2.0.50 → 2.0.60");
    let pm = row(&d, "proc-macro2");
    assert!(pm.integrity_changed);
    assert_eq!(pm.required_by, ["syn"]);
    let g = row(&d, "mygit");
    assert_eq!(g.kind, ChangeKind::Changed);
    assert_eq!(
        g.new_source.as_ref().unwrap().url.as_deref(),
        Some("https://github.com/acme/mygit")
    );
    assert!(
        g.compare_url()
            .unwrap()
            .contains("/compare/1111111111111111111111111111111111111111...2222")
    );
    assert_eq!(row(&d, "foo").kind, ChangeKind::Added);
    // Workspace member + syn 1.
    assert_eq!(d.unchanged, 2);
}

