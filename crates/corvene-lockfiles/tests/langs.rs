#[test]
fn mix_lock() {
    let old = r#"%{
  "castore": {:hex, :castore, "1.0.4", "ff4d0fb2e6411c0479b1d965a814ea6d00e51eb2f58697446e9c41a97d940b28", [:mix], [], "hexpm", "9418c1b8144e11656f0be99943db4caf04612e3eaecefb6dbaff6219e5d4ff8e"},
  "jason": {:hex, :jason, "1.4.1", "inner", [:mix], [{:decimal, "~> 1.0 or ~> 2.0", [hex: :decimal, repo: "hexpm", optional: true]}], "hexpm", "outer1"},
  "decimal": {:hex, :decimal, "2.1.1", "d1", [:mix], [], "hexpm", "d2"},
  "phoenix": {:hex, :phoenix, "1.7.10", "p1", [:mix], [{:castore, ">= 0.0.0", [hex: :castore, repo: "hexpm", optional: false]}, {:jason, "~> 1.0", [hex: :jason, repo: "hexpm", optional: true]}], "hexpm", "p2"},
  "my_dep": {:git, "https://github.com/acme/my_dep.git", "1111111111111111111111111111111111111111", [branch: "main"]},
}
"#;
    let new = old
        .replace("\"1.7.10\"", "\"1.7.11\"")
        .replace("\"d2\"", "\"d3\"")
        .replace(
            "1111111111111111111111111111111111111111",
            "2222222222222222222222222222222222222222",
        );
    let d = diff("mix.lock", old, &new);
    assert_eq!(row(&d, "phoenix").bump, Some(Bump::Patch));
    assert_eq!(
        row(&d, "phoenix").registry_url().as_deref(),
        Some("https://hex.pm/packages/phoenix/1.7.11")
    );
    let dec = row(&d, "decimal");
    assert!(dec.integrity_changed);
    assert_eq!(dec.required_by, ["jason"]);
    let g = row(&d, "my_dep");
    assert_eq!(g.version_label(), "main");
    assert!(g.compare_url().is_some());
    assert_eq!(d.unchanged, 2);
}

#[test]
fn rebar_lock() {
    let old = r#"{"1.2.0",
[{<<"cowboy">>,{pkg,<<"cowboy">>,<<"2.10.0">>},0},
 {<<"cowlib">>,{pkg,<<"cowlib">>,<<"2.12.1">>},1},
 {<<"mydep">>,
  {git,"https://github.com/acme/mydep.git",
       {ref,"1111111111111111111111111111111111111111"}},
  0}]}.
[
{pkg_hash,[
 {<<"cowboy">>, <<"AAA">>},
 {<<"cowlib">>, <<"BBB">>}]},
{pkg_hash_ext,[
 {<<"cowboy">>, <<"aaa">>},
 {<<"cowlib">>, <<"bbb">>}]}
].
"#;
    let new = old
        .replace("2.12.1", "2.13.0")
        .replace("<<\"aaa\">>", "<<\"aaa2\">>");
    let d = diff("rebar.lock", old, &new);
    let c = row(&d, "cowlib");
    assert_eq!((c.direct, c.bump), (Some(false), Some(Bump::Minor)));
    assert!(row(&d, "cowboy").integrity_changed);
    assert_eq!(row(&d, "cowboy").direct, Some(true));
    assert_eq!(d.unchanged, 1);
}

#[test]
fn cartfile_resolved() {
    let old = "github \"Alamofire/Alamofire\" \"5.8.0\"\ngit \"https://example.com/acme/thing.git\" \"1111111111\"\nbinary \"https://example.com/sdk.json\" \"1.0.0\"\n";
    let new = old.replace("5.8.0", "5.9.0").replace("1.0.0", "2.0.0");
    let d = diff("Cartfile.resolved", old, &new);
    assert_eq!(
        row(&d, "Alamofire/Alamofire").registry_url().as_deref(),
        Some("https://github.com/Alamofire/Alamofire")
    );
    assert_eq!(
        row(&d, "https://example.com/sdk.json").bump,
        Some(Bump::Major)
    );
    assert_eq!(
        row(&d, "Alamofire/Alamofire").ecosystem,
        Ecosystem::Carthage
    );
    assert_eq!(
        row(&d, "Alamofire/Alamofire")
            .new_source
            .as_ref()
            .map(|s| s.kind),
        Some(SourceKind::Git)
    );
}
